// Writes the theme overlays for the color presets to res/values/color_presets.xml.
// The output is committed, so run this by hand when the seeds change: npm install && npm run colors
// A new seed also needs an entry in the ColorPreset enum and a string for its name.

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { argbFromHex, Hct, hexFromArgb, SchemeTonalSpot } from '@material/material-color-utilities';

const SEEDS = {
    Indigo: '#3F51B5',
    Blue: '#2196F3',
    Teal: '#009688',
    Green: '#4CAF50',
    Amber: '#FFC107',
    Orange: '#FF9800',
    Red: '#F44336',
    Pink: '#E91E63',
    Purple: '#9C27B0',
    Brown: '#795548',
};

const STANDARD_CONTRAST = 0;

// theme attribute to scheme role
const ROLES = {
    colorPrimary: 'primary',
    colorOnPrimary: 'onPrimary',
    colorPrimaryContainer: 'primaryContainer',
    colorOnPrimaryContainer: 'onPrimaryContainer',
    colorPrimaryInverse: 'inversePrimary',
    colorSecondary: 'secondary',
    colorOnSecondary: 'onSecondary',
    colorSecondaryContainer: 'secondaryContainer',
    colorOnSecondaryContainer: 'onSecondaryContainer',
    colorTertiary: 'tertiary',
    colorOnTertiary: 'onTertiary',
    colorTertiaryContainer: 'tertiaryContainer',
    colorOnTertiaryContainer: 'onTertiaryContainer',
    colorAccent: 'primary',
    'android:colorBackground': 'background',
    colorOnBackground: 'onBackground',
    colorSurface: 'surface',
    colorOnSurface: 'onSurface',
    colorSurfaceVariant: 'surfaceVariant',
    colorOnSurfaceVariant: 'onSurfaceVariant',
    colorSurfaceDim: 'surfaceDim',
    colorSurfaceBright: 'surfaceBright',
    colorSurfaceContainerLowest: 'surfaceContainerLowest',
    colorSurfaceContainerLow: 'surfaceContainerLow',
    colorSurfaceContainer: 'surfaceContainer',
    colorSurfaceContainerHigh: 'surfaceContainerHigh',
    colorSurfaceContainerHighest: 'surfaceContainerHighest',
    colorSurfaceInverse: 'inverseSurface',
    colorOnSurfaceInverse: 'inverseOnSurface',
    colorOutline: 'outline',
    colorOutlineVariant: 'outlineVariant',
    // the app's own surfaces, which would otherwise keep the greys of the base themes
};

function overlay(name, seed, dark) {
    const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(seed)), dark, STANDARD_CONTRAST);
    const items = Object.entries(ROLES).map(([attribute, role]) => {
        const color = hexFromArgb(scheme[role]).toUpperCase();
        return `        <item name="${attribute}">${color}</item>`;
    });

    return [
        `    <style name="ThemeOverlay.Gelli.Color.${name}.${dark ? 'Dark' : 'Light'}" parent="">`,
        ...items,
        '    </style>',
    ].join('\n');
}

const overlays = Object.entries(SEEDS).flatMap(([name, seed]) => [
    `    <!-- ${name} ${seed} -->`,
    overlay(name, seed, false),
    '',
    overlay(name, seed, true),
    '',
]);

const xml = [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by scripts/generate_color_presets.mjs. Do not edit. -->',
    '<resources>',
    '',
    ...overlays,
    '</resources>',
    '',
].join('\n');

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
writeFileSync(resolve(root, 'app/src/main/res/values/color_presets.xml'), xml);
